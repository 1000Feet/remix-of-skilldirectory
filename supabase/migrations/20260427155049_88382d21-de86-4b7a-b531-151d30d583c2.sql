-- ---------- FUNCTIONS ----------
CREATE OR REPLACE FUNCTION public.is_admin(user_id uuid)
RETURNS boolean LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM public.admin_users WHERE user_id = $1);
$$;

CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN NEW.updated_at = NOW(); RETURN NEW; END; $$;

CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN NEW.updated_at = timezone('utc', now()); RETURN NEW; END; $$;

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF new.raw_user_meta_data->>'user_type' = 'student' THEN
    INSERT INTO public.student_profiles (user_id, email) VALUES (new.id, new.email);
  END IF;
  RETURN new;
END; $$;

CREATE OR REPLACE FUNCTION public.get_profile_view_count(educator_id uuid)
RETURNS TABLE(total_views bigint, unique_views bigint, last_24h_views bigint)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  RETURN QUERY
  SELECT count(*)::bigint,
         count(DISTINCT coalesce(viewer_id::text, ip_address))::bigint,
         count(*) FILTER (WHERE viewed_at > now() - interval '24 hours')::bigint
  FROM public.profile_views WHERE educator_profile_id = educator_id;
END; $$;

