-- ---------- RLS POLICIES ----------
CREATE POLICY "Allow admins to read admin_users" ON public.admin_users
  FOR SELECT TO authenticated USING (public.is_admin(auth.uid()));

CREATE POLICY "Allow public read access" ON public.api_keys FOR SELECT USING (true);

CREATE POLICY "Anyone can read categories" ON public.categories FOR SELECT USING (true);
CREATE POLICY "Admins can insert categories" ON public.categories FOR INSERT TO authenticated
  WITH CHECK (public.is_admin(auth.uid()));
CREATE POLICY "Admins can update categories" ON public.categories FOR UPDATE TO authenticated
  USING (public.is_admin(auth.uid()));
CREATE POLICY "Admins can delete categories" ON public.categories FOR DELETE TO authenticated
  USING (public.is_admin(auth.uid()));

CREATE POLICY "Users can read their own messages" ON public.chat_messages FOR SELECT TO authenticated
  USING (((auth.uid() = sender_id) OR (auth.uid() = receiver_id)) AND deleted_at IS NULL);
CREATE POLICY "Users can insert messages" ON public.chat_messages FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = sender_id);
CREATE POLICY "Users can delete their own messages" ON public.chat_messages FOR UPDATE TO authenticated
  USING (auth.uid() = sender_id) WITH CHECK (deleted_at IS NULL);

CREATE POLICY "Public read educator profiles" ON public.educator_profiles FOR SELECT USING (true);
CREATE POLICY "Insert own educator profile" ON public.educator_profiles FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Update own educator profile" ON public.educator_profiles FOR UPDATE TO authenticated
  USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Delete own educator profile" ON public.educator_profiles FOR DELETE TO authenticated
  USING (auth.uid() = user_id);
CREATE POLICY "Admins update all educator profiles" ON public.educator_profiles FOR UPDATE TO authenticated
  USING (public.is_admin(auth.uid())) WITH CHECK (public.is_admin(auth.uid()));

CREATE POLICY "Read student profiles" ON public.student_profiles FOR SELECT TO authenticated USING (true);
CREATE POLICY "Insert own student profile" ON public.student_profiles FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Update own student profile" ON public.student_profiles FOR UPDATE TO authenticated
  USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Admins update all student profiles" ON public.student_profiles FOR UPDATE TO authenticated
  USING (public.is_admin(auth.uid())) WITH CHECK (public.is_admin(auth.uid()));

CREATE POLICY "Anyone can read reviews" ON public.reviews FOR SELECT USING (true);
CREATE POLICY "Students can create reviews" ON public.reviews FOR INSERT TO authenticated
  WITH CHECK (EXISTS (SELECT 1 FROM student_profiles WHERE user_id = auth.uid()));
CREATE POLICY "Students update own reviews" ON public.reviews FOR UPDATE TO authenticated
  USING (EXISTS (SELECT 1 FROM student_profiles WHERE user_id = auth.uid() AND id = reviews.student_id));
CREATE POLICY "Students delete own reviews" ON public.reviews FOR DELETE TO authenticated
  USING (EXISTS (SELECT 1 FROM student_profiles WHERE user_id = auth.uid() AND id = reviews.student_id));

CREATE POLICY "Read reactions" ON public.review_reactions FOR SELECT USING (true);
CREATE POLICY "Insert own reaction" ON public.review_reactions FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Update own reaction" ON public.review_reactions FOR UPDATE USING (auth.uid() = user_id);
CREATE POLICY "Delete own reaction" ON public.review_reactions FOR DELETE USING (auth.uid() = user_id);

CREATE POLICY "Read replies" ON public.review_replies FOR SELECT USING (true);
CREATE POLICY "Insert own reply" ON public.review_replies FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Update own reply" ON public.review_replies FOR UPDATE USING (auth.uid() = user_id);
CREATE POLICY "Delete own reply" ON public.review_replies FOR DELETE USING (auth.uid() = user_id);

CREATE POLICY "Students view own lesson requests" ON public.lesson_requests FOR SELECT TO authenticated
  USING (student_id = auth.uid());
CREATE POLICY "Educators view own lesson requests" ON public.lesson_requests FOR SELECT TO authenticated
  USING (educator_id = auth.uid());
CREATE POLICY "Students create lesson requests" ON public.lesson_requests FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = student_id);
CREATE POLICY "Both update lesson requests" ON public.lesson_requests FOR UPDATE TO authenticated
  USING (educator_id = auth.uid() OR student_id = auth.uid());

CREATE POLICY "Anyone can insert profile views" ON public.profile_views FOR INSERT WITH CHECK (true);
CREATE POLICY "Educators view own profile views" ON public.profile_views FOR SELECT
  USING (auth.uid() IN (SELECT user_id FROM educator_profiles WHERE id = profile_views.educator_profile_id));

CREATE POLICY "View own memberships" ON public.memberships FOR SELECT
  USING (educator_id IN (SELECT id FROM educator_profiles WHERE user_id = auth.uid()));
CREATE POLICY "Insert own memberships" ON public.memberships FOR INSERT
  WITH CHECK (educator_id IN (SELECT id FROM educator_profiles WHERE user_id = auth.uid()));
CREATE POLICY "Update own memberships" ON public.memberships FOR UPDATE
  USING (educator_id IN (SELECT id FROM educator_profiles WHERE user_id = auth.uid()));

CREATE POLICY "View own payments" ON public.membership_payments FOR SELECT
  USING (membership_id IN (SELECT m.id FROM memberships m JOIN educator_profiles e ON e.id = m.educator_id WHERE e.user_id = auth.uid()));

CREATE POLICY "Admin read stripe" ON public.stripe_transactions FOR SELECT TO authenticated
  USING (public.is_admin(auth.uid()));

CREATE POLICY "Anyone can submit support" ON public.support_submissions FOR INSERT WITH CHECK (true);

CREATE POLICY "Admin insert env" ON public.environment_variables FOR INSERT
  WITH CHECK (public.is_admin(auth.uid()));
CREATE POLICY "Admin update env" ON public.environment_variables FOR UPDATE
  USING (public.is_admin(auth.uid()));
CREATE POLICY "Admin delete env" ON public.environment_variables FOR DELETE
  USING (public.is_admin(auth.uid()));

